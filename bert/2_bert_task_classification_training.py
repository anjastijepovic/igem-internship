# Function that returns overall and per-label metrics
def compute_multilabel_metrics(y_true, y_pred, label_names):
    overall_metrics = {
        "micro_precision": precision_score(y_true, y_pred, average="micro", zero_division=0),
        "micro_recall":    recall_score(y_true, y_pred, average="micro", zero_division=0),
        "micro_f1":        f1_score(y_true, y_pred, average="micro", zero_division=0),
        "macro_precision": precision_score(y_true, y_pred, average="macro", zero_division=0),
        "macro_recall":    recall_score(y_true, y_pred, average="macro", zero_division=0),
        "macro_f1":        f1_score(y_true, y_pred, average="macro", zero_division=0),
    }

    rows = []
    for j, label in enumerate(label_names):
        yt = y_true[:, j]
        yp = y_pred[:, j]

        tp = int(((yt == 1) & (yp == 1)).sum())
        fp = int(((yt == 0) & (yp == 1)).sum())
        fn = int(((yt == 1) & (yp == 0)).sum())
        tn = int(((yt == 0) & (yp == 0)).sum())

        rows.append({
            "label": label,
            "support_pos": int((yt == 1).sum()),
            "tp": tp,
            "fp": fp,
            "fn": fn,
            "tn": tn,
            "precision": precision_score(yt, yp, zero_division=0),
            "recall": recall_score(yt, yp, zero_division=0),
            "f1": f1_score(yt, yp, zero_division=0),
        })

    per_label_df = pd.DataFrame(rows)
    return overall_metrics, per_label_df

# Function to:
# 1. run the trained model on a dataset split (train/val/test)
# 2. turn probabilities into 0/1 predictions using thresholds 
# 3. compute metrics reusing previous function
# 4. save everything to CSV
def evaluate_split_and_save(split, loader, model, device, thresholds, label_names, output_dir):
    probs, true = get_probs_and_labels(model, loader, device)
    preds = apply_thresholds(probs, thresholds)

    overall_metrics, per_label_df = compute_multilabel_metrics(
        true.astype(int),
        preds.astype(int),
        label_names
    )

    # Save per-label metrics 
    per_label_df.to_csv(f"{output_dir}/{split}_per_label_metrics.csv", index=False)
    print(f"\nSaved per-label metrics to: {OUTPUT_DIR}/{split}_per_label_metrics.csv")

    return {"split": split, **overall_metrics} # merging two dictionaries


