# --------------------- DATASET CLASS ---------------------

class TextClassifierDataset(Dataset): # creates a dataset type compatible with PyTorch’s DataLoader
    def __init__(self, encodings, labels):
        self.encodings = encodings
        self.labels = labels

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx): # how PyTorch retrieves one training example from the dataset
        item = {key: torch.tensor(val[idx]) for key, val in self.encodings.items()}
        item["labels"] = torch.tensor(self.labels[idx], dtype=torch.float) #labels should be float because the loss is Binary Cross Entropy with Logits which expects floats
        return item

train_dataset = TextClassifierDataset(train_encodings, train_labels) # train_encodings are the encoded task description texts in the train df, while train_labels are the task labels in the train df
