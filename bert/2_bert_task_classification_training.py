# Function to compute POS WEIGHT - to be used in the loss function
# It tells loss: Positive examples are more important than negative examples for this label (so rare labels get amplified)
def compute_pos_weight(train_labels, device):

    Y_train = np.stack(train_labels)

    pos_counts = Y_train.sum(axis=0) # positives per label
    neg_counts = Y_train.shape[0] - pos_counts # negatives per label

    # Avoid division by 0 if a label has 0 positives - but it will always predict 0 for that label
    pos_weight = neg_counts / np.clip(pos_counts, 1, None)

    return torch.tensor(pos_weight, dtype=torch.float).to(device)

# Function for training one epoch
# It trains the model on the full training DataLoader once and returns average training loss
def train_one_epoch(model, loader, optimizer, scheduler, loss_fn, device):
    model.train()
    total_loss = 0

    # Add tqdm progress bar (I added it only for the training loop)
    for batch in tqdm(loader, desc="Training", leave=True):
        optimizer.zero_grad()

        input_ids = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        labels = batch["labels"].to(device).float()

        outputs = model(input_ids=input_ids, attention_mask=attention_mask)
        logits = outputs.logits

        loss = loss_fn(logits, labels)
        loss.backward()

        optimizer.step()
        scheduler.step()

        total_loss += loss.item()

    return total_loss / len(loader)


# Function for evaluation of loss (validation and test)
@torch.no_grad() # disables gradient tracking (not needed for val and test) to save memory and speed up evaluation
def evaluate(model, loader, loss_fn, device):
    model.eval()
    total_loss = 0

    for batch in loader:
        input_ids = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        labels = batch["labels"].to(device).float()

        outputs = model(input_ids=input_ids, attention_mask=attention_mask)
        logits = outputs.logits

        loss = loss_fn(logits, labels)
        total_loss += loss.item()

    return total_loss / len(loader) # average loss over all batches


# Helper functions for TUNING THRESHOLDS

# Function to get predicted probabilities on the validation set + true labels (to be used in threshold tuning)
@torch.no_grad()
def get_probs_and_labels(model, loader, device):
    model.eval()
    all_probs = []
    all_labels = []

    for batch in loader:
        input_ids = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        labels = batch["labels"].cpu().numpy()  # keep on CPU for numpy ops

        outputs = model(input_ids=input_ids, attention_mask=attention_mask)
        logits = outputs.logits

        probs = torch.sigmoid(logits).cpu().numpy()  # convert logits -> probabilities

        all_probs.append(probs)
        all_labels.append(labels)

    all_probs = np.vstack(all_probs)    # shape: (N, num_labels)
    all_labels = np.vstack(all_labels)  # shape: (N, num_labels)
    return all_probs, all_labels

# Function to tune best threshold per label (maximize F1)
def tune_thresholds_per_label(val_probs, val_labels, thresholds=None):
    if thresholds is None:
        thresholds = np.arange(0.1, 0.91, 0.05) # trying thresholds between 0.1 and 0.95 with step size 0.05 between them

    num_labels = val_labels.shape[1]
    best_thresholds = np.zeros(num_labels)

    for j in range(num_labels):
        best_t = 0.5
        best_f1 = -1
        y_true = val_labels[:, j].astype(int)

        for t in thresholds:
            y_pred = (val_probs[:, j] >= t).astype(int)
            f1 = f1_score(y_true, y_pred, zero_division=0)

            if f1 > best_f1:
                best_f1 = f1
                best_t = t

        best_thresholds[j] = best_t

    return best_thresholds


# Function to apply tuned thresholds to test predictions later
# Converts probabilities to final 0/1 predictions using a per-label threshold 
# e.g. if probability for conceptualization > conceptualization's best threshold --> conceptualization is 1)
def apply_thresholds(probs, thresholds):
    # Make thresholds shape (1, num_labels) so it can compare against all rows
    thresholds_matrix = thresholds.reshape(1, -1)

    # Compare each probability to its label threshold -> True/False
    meets_threshold = probs >= thresholds_matrix

    # Convert True/False to 1/0 integers
    preds = meets_threshold.astype(int)

    return preds


